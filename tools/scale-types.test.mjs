import './test-sandbox.mjs'
import './renderer-test-fonts.mjs'
import test from 'node:test'
import assert from 'node:assert/strict'
import { createCanvasSnapshot } from '../model/index.js'
import { executeCanvasCommands } from '../engine/index.js'
import { getShapePageBounds, shapeToPagePoint } from '../renderer/geometry.js'

const subject = 'shape:subject'
function lineFixture() {
  const snapshot = createCanvasSnapshot()
  const page = Object.values(snapshot.store).find(r => r.typeName === 'page').id
  return executeCanvasCommands(snapshot, [{ type: 'put', record: {
    id: subject, typeName: 'shape', type: 'line', parentId: page, index: 'a1',
    x: 300, y: 250, rotation: 0, opacity: 1, isLocked: false, meta: {},
    props: { color: 'black', dash: 'solid', size: 'm', scale: 1, spline: 'line', points: {
      a1: { id: 'a1', index: 'a1', x: 0, y: 0 },
      a2: { id: 'a2', index: 'a2', x: 90, y: 100 },
      a3: { id: 'a3', index: 'a3', x: 200, y: 40 },
    } },
  } }]).snapshot
}

function arrowFixture(kind = 'arc') {
  return executeCanvasCommands(createCanvasSnapshot(), [{
    type: 'create_shape', id: subject, shapeType: 'arrow', x: 300, y: 250,
    props: { kind, start: { x: 0, y: 0 }, end: { x: 200, y: 100 }, bend: kind === 'arc' ? 50 : 0, elbowMidPoint: .3 },
  }]).snapshot
}

for (const mode of ['resize_bounds', 'scale_shape']) test(`${mode}：线条变换控制点，保留点身份、样式和线宽比例`, () => {
  const before = lineFixture(), original = structuredClone(before)
  const result = executeCanvasCommands(before, [{ type: 'scale_shapes', ids: [subject], origin: { x: 300, y: 250 }, scale: { x: 2, y: 1.5 }, mode }])
  const shape = result.snapshot.store[subject]
  // Independent legacy public-runtime observation, 2026-11-25; these values
  // were measured with the same origin and factors, not generated by the rule.
  assert.deepEqual(shape.props.points, {
    a1: { id: 'a1', index: 'a1', x: 0, y: 0 },
    a2: { id: 'a2', index: 'a2', x: 180, y: 150 },
    a3: { id: 'a3', index: 'a3', x: 400, y: 60 },
  })
  assert.deepEqual([shape.x, shape.y, shape.props.scale, shape.props.spline], [300, 250, 1, 'line'])
  assert.deepEqual(before, original)
})

test('线条反射保留记录原点，带符号的控制点只反射一次', () => {
  const result = executeCanvasCommands(lineFixture(), [{ type: 'scale_shapes', ids: [subject], origin: { x: 300, y: 250 }, scale: { x: -2, y: 1.5 } }])
  const shape = result.snapshot.store[subject]
  assert.deepEqual([shape.x, shape.y, shape.props.points.a2.x, shape.props.points.a2.y], [300, 250, -180, 150])
  assert.deepEqual(getShapePageBounds(result.snapshot, subject), { x: -100, y: 250, w: 400, h: 150 })
})

test('水平线条仍是缩放目标，不因包围框零高度被丢弃', () => {
  const before = lineFixture()
  for (const point of Object.values(before.store[subject].props.points)) point.y = 0
  const result = executeCanvasCommands(before, [{ type: 'scale_shapes', ids: [subject], origin: { x: 300, y: 250 }, scale: { x: 2, y: 1.5 } }])
  assert.equal(result.snapshot.store[subject].props.points.a3.x, 400)
  assert.deepEqual(result.results[0].shapeIds, [subject])
})

test('有旋转的线条在画布轴反射，世界控制点只反射一次', () => {
  const before = lineFixture()
  before.store[subject].rotation = Math.PI / 4
  const result = executeCanvasCommands(before, [{ type: 'scale_shapes', ids: [subject], origin: { x: 300, y: 250 }, scale: { x: -2, y: 2 } }])
  const shape = result.snapshot.store[subject]
  const point = shapeToPagePoint(result.snapshot, subject, shape.props.points.a2)
  assert.ok(Math.abs(point.x - 314.14213562373095) < 1e-8)
  assert.ok(Math.abs(point.y - 518.7005768508881) < 1e-8)
})

for (const mode of ['resize_bounds', 'scale_shape']) for (const kind of ['arc', 'elbow']) test(`${mode}：${kind} 箭头缩放端点并保留线宽及肘点参数`, () => {
  const before = arrowFixture(kind)
  const result = executeCanvasCommands(before, [{ type: 'scale_shapes', ids: [subject], origin: { x: 300, y: 250 }, scale: { x: 2, y: 1.5 }, mode }])
  const shape = result.snapshot.store[subject]
  assert.deepEqual([shape.x, shape.y, shape.props.start, shape.props.end, shape.props.bend, shape.props.elbowMidPoint, shape.props.scale],
    [300, 250, { x: 0, y: 0 }, { x: 400, y: 150 }, kind === 'arc' ? 100 : 0, .3, 1])
})

test('弧形箭头单轴反射反转弯曲方向，双轴反射保留方向', () => {
  for (const [x, y, bend] of [[-2, 1.5, -100], [-2, -1.5, 100], [2, -1.5, -100]]) {
    const result = executeCanvasCommands(arrowFixture(), [{ type: 'scale_shapes', ids: [subject], origin: { x: 300, y: 250 }, scale: { x, y } }])
    assert.equal(result.snapshot.store[subject].props.bend, bend)
    assert.deepEqual(result.snapshot.store[subject].props.end, { x: x < 0 ? -400 : 400, y: y < 0 ? -150 : 150 })
  }
})

for (const count of [1, 2]) test(`${count}端绑定箭头仅缩放未绑定的原始端点，绑定记录保持原样`, () => {
  let before = arrowFixture()
  before.store[subject].props.start = { x: 40, y: 20 }
  const terminals = count === 2 ? ['start', 'end'] : ['end']
  before = executeCanvasCommands(before, terminals.flatMap((terminal, i) => [
    { type: 'create_shape', id: `shape:target-${terminal}`, shapeType: 'geo', x: 600 + i * 200, y: 340, props: { w: 100, h: 100, fill: 'solid' } },
    { type: 'put', record: { id: `binding:${terminal}`, typeName: 'binding', type: 'arrow', fromId: subject, toId: `shape:target-${terminal}`, meta: {}, props: { terminal, normalizedAnchor: { x: .5, y: .5 }, isExact: true, isPrecise: true, snap: 'none' } } },
  ])).snapshot
  const result = executeCanvasCommands(before, [{ type: 'scale_shapes', ids: [subject], origin: { x: 300, y: 250 }, scale: { x: 2, y: 1.5 } }])
  const arrow = result.snapshot.store[subject]
  assert.deepEqual(arrow.props.end, { x: 200, y: 100 })
  assert.deepEqual(arrow.props.start, count === 2 ? { x: 40, y: 20 } : { x: 80, y: 30 })
  assert.equal(arrow.props.bend, 100)
  for (const terminal of terminals) assert.deepEqual(result.snapshot.store[`binding:${terminal}`], before.store[`binding:${terminal}`])
})

for (const axis of ['x', 'y']) test(`单轴退化的${axis === 'x' ? '竖' : '横'}线缩放仍保留三点与零轴`, () => {
  const before = lineFixture()
  for (const point of Object.values(before.store[subject].props.points)) point[axis] = 0
  const result = executeCanvasCommands(before, [{ type: 'scale_shapes', ids: [subject], origin: { x: 300, y: 250 }, scale: { x: 2, y: 1.5 } }])
  const points = result.snapshot.store[subject].props.points
  assert.deepEqual([points.a1[axis], points.a2[axis], points.a3[axis]], [0, 0, 0])
  assert.equal(axis === 'x' ? points.a2.y : points.a3.x, axis === 'x' ? 150 : 400)
  assert.equal(Object.keys(points).length, 3)
})

test('组内水平线不被筛掉，父组保持原样', () => {
  let before = lineFixture()
  for (const point of Object.values(before.store[subject].props.points)) point.y = 0
  before = executeCanvasCommands(before, [
    { type: 'create_shape', id: 'shape:g', shapeType: 'group', x: 100, y: 50 },
    { type: 'create_shape', id: 'shape:p', shapeType: 'geo', parentId: 'shape:g', x: 500, y: 300, props: { w: 100, h: 100 } },
    { type: 'update', id: subject, changes: { parentId: 'shape:g' } },
  ]).snapshot
  const result = executeCanvasCommands(before, [{ type: 'scale_shapes', ids: ['shape:g'], origin: { x: 400, y: 300 }, scale: { x: 2, y: 3 } }])
  const points = result.snapshot.store[subject].props.points
  assert.deepEqual([points.a1.y, points.a2.y, points.a3.y, points.a3.x], [0, 0, 0, 400])
  assert.deepEqual(result.snapshot.store['shape:g'], before.store['shape:g'])
})

for (const command of [
  { type: 'align_shapes', alignment: 'left' },
  { type: 'rotate_shapes', origin: { x: 0, y: 0 }, angle: Math.PI / 2 },
  { type: 'flip_shapes', axis: 'x' },
]) test(`${command.type} 默认筛选仍跳过零高度线条`, () => {
  let before = lineFixture()
  for (const point of Object.values(before.store[subject].props.points)) point.y = 0
  before = executeCanvasCommands(before, [
    { type: 'create_shape', id: 'shape:peer', shapeType: 'geo', x: 700, y: 300, props: { w: 100, h: 100 } },
    { type: 'create_shape', id: 'shape:peer2', shapeType: 'geo', x: 1000, y: 400, props: { w: 50, h: 50 } },
  ]).snapshot
  const result = executeCanvasCommands(before, [{ ...command, ids: [subject, 'shape:peer', 'shape:peer2'] }])
  assert.deepEqual(result.snapshot.store[subject], before.store[subject])
  assert.equal(result.results[0].shapeIds.includes(subject), false)
})

for (const count of [1, 2]) test(`${count}端绑定箭头随目标缩放后，派生端点和增量索引使用新位置`, async () => {
  const { getConnectionGeometry, createSpatialIndex } = await import('../renderer/geometry.js')
  let before = arrowFixture()
  before.store[subject].props.bend = 0
  before.store[subject].props.arrowheadEnd = 'none'
  const terminals = count === 2 ? [['start', 100, 100], ['end', 600, 340]] : [['end', 600, 340]]
  before = executeCanvasCommands(before, terminals.flatMap(([terminal, x, y]) => [
    { type: 'create_shape', id: `shape:${terminal}`, shapeType: 'geo', x, y, props: { w: 100, h: 100, fill: 'solid' } },
    { type: 'put', record: { id: `binding:${terminal}`, typeName: 'binding', type: 'arrow', fromId: subject, toId: `shape:${terminal}`, meta: {}, props: { terminal, normalizedAnchor: { x: .5, y: .5 }, isExact: true, isPrecise: true, snap: 'none' } } },
  ])).snapshot
  const result = executeCanvasCommands(before, [{ type: 'scale_shapes', ids: terminals.map(([terminal]) => `shape:${terminal}`), origin: { x: 300, y: 250 }, scale: { x: 2, y: 1.5 } }])
  const arrow = result.snapshot.store[subject], geometry = getConnectionGeometry(arrow, result.snapshot)
  assert.deepEqual(arrow, before.store[subject])
  assert.deepEqual(geometry.contacts.end, { x: 700, y: 210 })
  if (count === 2) assert.deepEqual(geometry.contacts.start, { x: -300, y: -150 })
  const index = createSpatialIndex(Object.values(before.store))
  index.applyChanges(result.changes)
  assert.ok(index.getUpdateStats().updatedIds.includes(subject))
  // The exact-bound straight body joins (300,250)/(0,100) to (1000,460).
  const point = count === 2 ? { x: 500, y: 280 } : { x: 650, y: 355 }
  assert.equal(index.hitTest(point), subject)
  if (count === 1) assert.notEqual(index.hitTest({ x: 475, y: 320 }), subject)
})
