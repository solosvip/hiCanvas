const graphemes = new Intl.Segmenter(undefined, { granularity: 'grapheme' })
export const splitNoteCharacters = text => [...graphemes.segment(text)].map(item => item.segment)
export const NOTE_FONT_FAMILIES = Object.freeze({ draw: 'sans-serif', sans: 'sans-serif', serif: 'serif', mono: 'monospace' })

export function measureNoteText(text, size, font = 'draw') {
  const table = advances[font] || advances.draw
  let width = 0
  for (const char of splitNoteCharacters(text)) {
    const base = char.normalize('NFD').replace(/\p{Mark}/gu, '')
    const index = base ? characters.indexOf(base === '\u00a0' ? ' ' : base) : -1
    if (!base) continue
    width += index >= 0 ? table[index] / 64 : /[^\u0000-\u024f]/u.test(char) ? 22 : 11
  }
  return width * size / 22
}
